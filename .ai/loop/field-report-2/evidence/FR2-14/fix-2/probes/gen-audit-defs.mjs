// Generates fix-2/probes/mutants-audit.mjs from the auditors' own mutant lists (read-only: their files are never edited):
//   audit-1: fix-1/audit-probes-rerun/mutants.mjs (the M array)      -> ids A*
//   audit-2: audit-2/probes/mutants-def.mjs (a module)               -> ids B*
// and reports, for every mutant, how many times its find-string occurs in the CURRENT source (it must be exactly 1 to run).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
const HERE = path.dirname(fileURLToPath(import.meta.url));
const WT = path.resolve(HERE, '../../../../../../..');
const EV = path.join(WT, '.ai/loop/field-report-2/evidence/FR2-14');
const out = {};
// audit-1
const a1 = fs.readFileSync(path.join(EV, 'fix-1/audit-probes-rerun/mutants.mjs'), 'utf8');
const s = a1.indexOf('const M = [');
const e = a1.indexOf('];\nconst DEP');
const CP = 'packages/capability-runtime/src/config-precedence.ts';
const PC = 'packages/capability-runtime/src/project-config.ts';
const arr = new Function('CP', 'PC', `return ${a1.slice(s + 'const M = '.length, e + 1)};`)(CP, PC);
for (const m of arr) out[m.id] = { desc: 'audit-1 ' + m.id + ': ' + m.desc, file: m.file, pkg: (m.pkgs?.[0] ?? (m.file.includes('mcp-server') ? 'mcp-server' : m.file.includes('/cli/') ? 'cli' : 'capability-runtime')).replace('@sutradhar/', ''), find: m.from, replace: m.to };
// audit-2
const b = (await import(pathToFileURL(path.join(EV, 'audit-2/probes/mutants-def.mjs')).href)).MUTANTS;
for (const [id, m] of Object.entries(b)) {
  if (id === 'B15') continue; // harness mutant, not a catch test
  out[id] = { desc: 'audit-2 ' + id + ': ' + m.desc, file: m.file, pkg: m.pkg.replace('@sutradhar/', ''), find: m.find, replace: m.replace };
}
const report = [];
for (const [id, m] of Object.entries(out)) {
  const t = fs.readFileSync(path.join(WT, m.file), 'utf8').replace(/\r\n/g, '\n');
  const n = t.split(m.find.replace(/\r\n/g, '\n')).length - 1;
  report.push({ id, occurrences: n });
}
fs.writeFileSync(path.join(HERE, 'mutants-audit.mjs'), '// GENERATED by gen-audit-defs.mjs from the auditors\' mutant lists (unchanged find/replace text).\nexport const MUTANTS = ' + JSON.stringify(out, null, 1) + ';\n');
console.log(JSON.stringify(report));
